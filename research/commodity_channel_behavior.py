#!/usr/bin/env python3
"""What does Kalshi's `pyth_value` channel actually do when the price does not change?

This exists because of one ambiguity the desk cannot resolve by reading documentation. Kalshi
describes the channel as deduplicated. That says repeats are removed. It does not say whether a
message is emitted on every scheduled source update when the value has not moved. So a silence has
two explanations:

  1. the upstream source published nothing, or
  2. the value did not change and the venue sent nothing.

The desk currently refuses to distinguish them, blocks conservatively on any observation it cannot
vouch for, and says "reference observation too old" rather than diagnosing the venue. This report
is the measurement that would let the interpretation be strengthened.

The decisive statistic is `unchanged_value_messages`. A channel that suppresses unchanged values
can never send one, so a single occurrence proves it does not suppress them - and therefore that a
silence really is the source going quiet. Zero occurrences over a long recording is consistent
with suppression but does not prove it, because a genuinely busy feed may simply never repeat.

It also prints the message-gap distribution per symbol, because the gap limit the desk trades
against should be set from what the feed does rather than from a number someone typed.

Usage:
  python3 research/commodity_channel_behavior.py                       # writes reports/
  python3 research/commodity_channel_behavior.py --db path.sqlite
  python3 research/commodity_channel_behavior.py --self-test
"""
import argparse
import collections
import os
import sqlite3
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DB = os.path.join(HERE, '..', 'data', 'desk.sqlite')
OUT = os.path.join(HERE, '..', 'reports', 'commodity_channel_behavior.md')

# Below this, the report describes and refuses to conclude. One quiet hour on one symbol is not
# evidence about a channel's emit policy.
MIN_MINUTES_TO_CONCLUDE = 240
MIN_MESSAGES_TO_CONCLUDE = 50000


def pct(sorted_vals, q):
    if not sorted_vals:
        return None
    i = min(len(sorted_vals) - 1, max(0, int(round(q * (len(sorted_vals) - 1)))))
    return sorted_vals[i]


def gather(con):
    """One row per symbol. Reads the recorded observations, not the live feed."""
    have = {r[0] for r in con.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    if 'commodity_reference' not in have:
        return {}, 'no commodity_reference table: the feed has never been created in this database'
    cols = {r[1] for r in con.execute('PRAGMA table_info(commodity_reference)')}
    if 'message_gap_ms' not in cols:
        return {}, ('this database predates the session-18 observability fields; its gap_ms column '
                    'asserted something about the source that could not be observed, so it is not '
                    'read here')
    out = {}
    for symbol, in con.execute('SELECT DISTINCT symbol FROM commodity_reference'):
        rows = list(con.execute(
            'SELECT ts_received, price, message_gap_ms, value_changed, observed_value_fresh '
            'FROM commodity_reference WHERE symbol=? ORDER BY ts_received, id', (symbol,)))
        if len(rows) < 2:
            continue
        gaps = sorted(g for _, _, g, _, _ in rows if g and g > 0)
        changes = sum(1 for *_x, c, _f in rows if c)
        unchanged = sum(1 for *_x, c, _f in rows if not c)
        span = rows[-1][0] - rows[0][0]
        out[symbol] = {
            'messages': len(rows),
            'minutes': span / 60.0 if span > 0 else 0.0,
            'value_changes': changes,
            'unchanged_value_messages': unchanged,
            'gaps': gaps,
            'not_fresh': sum(1 for *_x, _c, f in rows if not f),
        }
    return out, None


def render(stats, note):
    lines = []
    w = lines.append
    w('# What the `pyth_value` channel does when the price does not move')
    w('')
    w('Generated by `research/commodity_channel_behavior.py`. Every number here is measured from')
    w('`commodity_reference`, which is what the desk recorded, not from documentation.')
    w('')
    w('## The question')
    w('')
    w('Kalshi documents this channel as deduplicated. That tells us repeats are removed. It does')
    w('not tell us whether a message is emitted on every scheduled source update when the value')
    w('has not changed. Until that is settled, a silence on the wire has two explanations - the')
    w('source published nothing, or the value did not move and the venue sent nothing - and the')
    w('desk treats them as indistinguishable, blocking on any observation whose recency it cannot')
    w('verify and saying so in those words.')
    w('')
    w('The decisive statistic is the last column. **A channel that suppresses unchanged values can')
    w('never send one.** One occurrence settles it.')
    w('')
    if note:
        w(f'> No data: {note}.')
        w('')
        w('The feed has to run before this report means anything.')
        return '\n'.join(lines) + '\n'
    if not stats:
        w('> No observations recorded yet. The feed has to run before this report means anything.')
        return '\n'.join(lines) + '\n'

    w('## Per symbol')
    w('')
    w('| symbol | minutes | messages | msg/s | changes/s | median gap | p95 | p99 | longest | unchanged-value messages |')
    w('|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|')
    total_minutes = 0.0
    total_messages = 0
    total_unchanged = 0
    for symbol in sorted(stats):
        s = stats[symbol]
        mins, n, gaps = s['minutes'], s['messages'], s['gaps']
        total_minutes = max(total_minutes, mins)
        total_messages += n
        total_unchanged += s['unchanged_value_messages']
        secs = max(mins * 60.0, 1e-9)
        w(f"| `{symbol}` | {mins:,.1f} | {n:,} | {n/secs:.2f} | {s['value_changes']/secs:.2f} | "
          f"{pct(gaps,0.5) or 0:,} ms | {pct(gaps,0.95) or 0:,} ms | {pct(gaps,0.99) or 0:,} ms | "
          f"{(gaps[-1] if gaps else 0):,} ms | {s['unchanged_value_messages']:,} |")
    w('')
    w('Gaps are between consecutive recorded observations of that symbol. Note that the desk')
    w('samples what it records (`record_min_interval_ms`, plus always the minute-closing tick), so')
    w('these are gaps in the RECORD, and are an upper bound on the gaps on the wire.')
    w('')

    w('## What follows from it')
    w('')
    enough = total_minutes >= MIN_MINUTES_TO_CONCLUDE and total_messages >= MIN_MESSAGES_TO_CONCLUDE
    if total_unchanged > 0:
        w(f'**The channel emits unchanged values.** {total_unchanged:,} messages carried a price')
        w('identical to the previous one for that symbol. A channel that suppressed unchanged')
        w('values could not do that, so a silence on this feed is the source going quiet rather')
        w('than the venue having nothing to send.')
        w('')
        w('That is enough to strengthen the interpretation: `message_gap_ms` may be read as')
        w('evidence about the source, the volatility estimator\'s `DropUncertain` policy is the')
        w('correct one, and a stale-source reason string would be accurate.')
    elif not enough:
        w(f'**Not enough recording to conclude.** {total_minutes:,.0f} minutes and')
        w(f'{total_messages:,} messages, against a bar of {MIN_MINUTES_TO_CONCLUDE:,} minutes and')
        w(f'{MIN_MESSAGES_TO_CONCLUDE:,} messages. No unchanged-value message has been seen, which')
        w('is consistent with suppression and also with a feed that simply never repeated in this')
        w('window. Both readings survive, so the conservative one stands.')
    else:
        w('**No unchanged-value message in a long recording.** That is consistent with the channel')
        w('suppressing unchanged values, and it is not proof: a feed whose price moves on every')
        w('scheduled update would look identical. The conservative interpretation therefore')
        w('stands - `message_gap_ms` remains a statement about our observation, and the desk keeps')
        w('saying "reference observation too old" rather than "the source stopped publishing".')
        w('')
        w('What would settle it: a documented statement from the venue about the emit policy, or')
        w('a period when the underlying is genuinely static (a market holiday) during which')
        w('messages either continue or stop.')
    w('')
    w('## What the desk does in the meantime')
    w('')
    w('- `observed_value_fresh` gates trading on `message_gap_ms`, because the desk should not')
    w('  price from a value whose recency it cannot verify. That is a claim about us.')
    w('- `unchanged_age_ms` is recorded separately, because "the value has not moved for 30s" and')
    w('  "we have not heard anything for 30s" are different facts and only one of them is')
    w('  evidence about the feed.')
    w('- The volatility estimator\'s treatment of returns spanning a silence is a named setting')
    w('  (`VolSettings::GapPolicy`) with both positions documented, not a constant in a loop. The')
    w('  research ladder races them.')
    return '\n'.join(lines) + '\n'


def self_test():
    con = sqlite3.connect(':memory:')
    con.execute('CREATE TABLE commodity_reference(id INTEGER PRIMARY KEY AUTOINCREMENT,'
                'ts_received INTEGER, symbol TEXT, price REAL, message_gap_ms INTEGER,'
                'unchanged_age_ms INTEGER, value_changed INTEGER, observed_value_fresh INTEGER)')
    base = 1789000000
    # A feed that repeats itself: the decisive case.
    for i in range(100):
        changed = 1 if i % 10 == 0 else 0
        con.execute('INSERT INTO commodity_reference(ts_received,symbol,price,message_gap_ms,'
                    'unchanged_age_ms,value_changed,observed_value_fresh) VALUES(?,?,?,?,?,?,?)',
                    (base + i, 'Metal.Index.GOLD/USD', 4300 + i // 10, 1000, 0, changed, 1))
    stats, note = gather(con)
    assert note is None and 'Metal.Index.GOLD/USD' in stats
    s = stats['Metal.Index.GOLD/USD']
    assert s['unchanged_value_messages'] == 90, s
    text = render(stats, None)
    assert 'The channel emits unchanged values' in text
    assert 'DropUncertain' in text

    # A feed that never repeats, and too short to conclude from.
    con2 = sqlite3.connect(':memory:')
    con2.execute('CREATE TABLE commodity_reference(id INTEGER PRIMARY KEY AUTOINCREMENT,'
                 'ts_received INTEGER, symbol TEXT, price REAL, message_gap_ms INTEGER,'
                 'unchanged_age_ms INTEGER, value_changed INTEGER, observed_value_fresh INTEGER)')
    for i in range(100):
        con2.execute('INSERT INTO commodity_reference(ts_received,symbol,price,message_gap_ms,'
                     'unchanged_age_ms,value_changed,observed_value_fresh) VALUES(?,?,?,?,?,?,?)',
                     (base + i, 'Metal.Index.GOLD/USD', 4300 + i, 1000, 0, 1, 1))
    text2 = render(gather(con2)[0], None)
    assert 'Not enough recording to conclude' in text2, text2
    assert 'The channel emits unchanged values' not in text2
    # And the ambiguity is never resolved by silence alone, however long the recording.
    con3 = sqlite3.connect(':memory:')
    con3.execute('CREATE TABLE commodity_reference(id INTEGER PRIMARY KEY AUTOINCREMENT,'
                 'ts_received INTEGER, symbol TEXT, price REAL, message_gap_ms INTEGER,'
                 'unchanged_age_ms INTEGER, value_changed INTEGER, observed_value_fresh INTEGER)')
    rows = [(base + i, 'Metal.Index.GOLD/USD', 4300 + i * 0.01, 1000, 0, 1, 1)
            for i in range(0, MIN_MESSAGES_TO_CONCLUDE + 10)]
    con3.executemany('INSERT INTO commodity_reference(ts_received,symbol,price,message_gap_ms,'
                     'unchanged_age_ms,value_changed,observed_value_fresh) VALUES(?,?,?,?,?,?,?)', rows)
    text3 = render(gather(con3)[0], None)
    assert 'is not proof' in text3, text3
    assert 'conservative interpretation therefore' in text3

    # An old database is described, not misread.
    con4 = sqlite3.connect(':memory:')
    con4.execute('CREATE TABLE commodity_reference(id INTEGER PRIMARY KEY, symbol TEXT, gap_ms INTEGER)')
    stats4, note4 = gather(con4)
    assert not stats4 and 'predates' in note4
    print('self-test OK: a repeated value settles the question, a short recording refuses to,')
    print('  a long one without repeats still refuses to, and a pre-session-18 database is not read.')


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--db', default=DB)
    ap.add_argument('--out', default=OUT)
    ap.add_argument('--self-test', action='store_true')
    args = ap.parse_args()
    if args.self_test:
        self_test()
        return
    if not os.path.exists(args.db):
        raise SystemExit(f'no database at {args.db}')
    con = sqlite3.connect(f'file:{args.db}?mode=ro', uri=True)
    stats, note = gather(con)
    text = render(stats, note)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w') as f:
        f.write(text)
    print(text)
    print(f'written to {args.out}')


if __name__ == '__main__':
    main()
